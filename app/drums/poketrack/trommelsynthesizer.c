static inline float pt_fmodf(float x, float y) { return x - fm_floorf(x / y) * y; }

typedef struct {
  float ic1, ic2, g, k, a1, a2, a3;
} Svf;

static void svf_set(Svf* s, float fc, float q, float sr) {
  if (fc > sr * 0.45f)
    fc = sr * 0.45f;
  s->g = fm_tanf(M_PI * fc / sr);
  s->k = 1.0f / q;
  s->a1 = 1.0f / (1.0f + s->g * (s->g + s->k));
  s->a2 = s->g * s->a1;
  s->a3 = s->g * s->a2;
}

static void svf_tick(Svf* s, float x, float* lp, float* bp, float* hp) {
  float v3 = x - s->ic2;
  float v1 = s->a1 * s->ic1 + s->a2 * v3;
  float v2 = s->ic2 + s->a2 * s->ic1 + s->a3 * v3;
  s->ic1 = 2 * v1 - s->ic1;
  s->ic2 = 2 * v2 - s->ic2;
  *bp = v1;
  *lp = v2;
  *hp = x - s->k * v1 - v2;
}

static inline float blep(float t, float dt) {
  if (t < dt) {
    t /= dt;
    return t + t - t * t - 1.0f;
  }
  if (t > 1.0f - dt) {
    t = (t - 1.0f) / dt;
    return t * t + t + t + 1.0f;
  }
  return 0.0f;
}

static inline float square(float ph, float dt) {
  float s = ph < 0.5f ? 1.0f : -1.0f;
  s += blep(ph, dt);
  s -= blep(ph < 0.5f ? ph + 0.5f : ph - 0.5f, dt);
  return s;
}

static inline float onepole_a(float fc, float sr) { return 1.0f - fm_expf(-TAU * fc / sr); }


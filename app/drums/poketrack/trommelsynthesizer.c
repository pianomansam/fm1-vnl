static inline float rnd(Voice* v) {
  v->rng ^= v->rng << 13;
  v->rng ^= v->rng >> 17;
  v->rng ^= v->rng << 5;
  return (float)(int32_t)v->rng / 2147483648.0f;
}

/* envelope i: exp(-t / tau) from t = 0, a factor a sample (env: its value now, then a sample on) */
static void env_set(Voice* v, int i, float tau) {
  v->ev[i] = 1.0f;
  v->ek[i] = fm_expf(-v->dt / tau);
}
static inline float env(Voice* v, int i) {
  float e = v->ev[i];
  v->ev[i] *= v->ek[i];
  return e;
}

static inline float decay_scale(float d) { return fm_powf(2.0f, (d - 0.5f) * 3.0f); }
static inline float tone_scale(float t, float range) { return fm_powf(2.0f, (t - 0.5f) * range); }

static const float METAL[6] = {205.3f, 304.4f, 369.6f, 522.7f, 540.0f, 800.0f};

static void voice_init(Voice* v, int semis) {
  const Cfg* c = v->cfg;
  const float* p = v->p;
  float tr = fm_powf(2.0f, (p[P_TUNE] + semis) / 12.0f);
  float ds = decay_scale(p[P_DECAY]);
  float tn = p[P_TONE];
  float ex = p[P_EXTRA];
  v->t = 0;
  v->rng = 0x9E3779B9u ^ (uint32_t)(v->voice * 2654435761u);
  v->lp1 = v->lp2 = 0;
  memset(v->ph, 0, sizeof v->ph);
  memset(&v->s1, 0, sizeof v->s1);
  memset(&v->s2, 0, sizeof v->s2);
  memset(&v->s3, 0, sizeof v->s3);
  switch (c->kind) {
    case K_SWEPT:
      v->f0 = c->c[0] * tr;
      v->famt = c->c[1];
      v->ftau = c->c[2];
      v->atau = c->c[3] * ds;
      v->click = c->c[4] * 2.0f * ex * (c->c[8] > 0 ? 1.0f : 2.0f * tn);
      v->ca = onepole_a(c->c[5] * (c->c[8] > 0 ? 1.0f : tone_scale(tn, 3.0f)), v->sr);
      v->drive = c->c[6] * (c->c[8] > 0 ? 0.4f + 1.2f * tn : 1.0f);
      v->nbody = c->c[7];
      env_set(v, 0, v->ftau);
      env_set(v, 1, v->atau);
      env_set(v, 2, 0.0015f);
      v->idrive = 1.0f / fm_tanhf(v->drive);
      break;
    case K_SNARE:
      v->aux[0] = c->c[0] * tr;
      v->aux[1] = c->c[1] * tr;
      v->aux[2] = c->c[2] * ds;
      v->aux[3] = c->c[3] * ds;
      v->aux[4] = c->c[7] * ds * (0.6f + 0.8f * ex);
      v->aux[5] = c->c[8] * (0.3f + 1.4f * ex);
      v->aux[6] = 0.5f + tn;  // osc2 balance
      svf_set(&v->s1, c->c[5], 0.7f, v->sr);
      v->ca = onepole_a(c->c[6] * tone_scale(tn, 2.0f), v->sr);
      env_set(v, 0, 0.015f);
      env_set(v, 1, v->aux[2]);
      env_set(v, 2, v->aux[3]);
      env_set(v, 3, v->aux[4]);
      env_set(v, 4, 0.0007f);
      break;
    case K_METAL:
      for (int i = 0; i < 6; i++) v->fr[i] = METAL[i] * c->c[0] * tr;
      svf_set(&v->s1, c->c[1] * tr, 1.2f, v->sr);
      svf_set(&v->s2, c->c[2] * tone_scale(tn, 1.2f), 0.7f, v->sr);
      v->aux[0] = c->c[3] * ds;
      v->aux[1] = c->c[4] * ds;
      v->aux[2] = fm_minf(1.0f, fm_maxf(0.0f, c->c[5] * (0.4f + 1.2f * tn)));
      env_set(v, 0, v->aux[0]);
      env_set(v, 1, v->aux[1]);
      env_set(v, 2, 0.0008f);
      break;
    case K_PING:
      v->aux[0] = c->c[0] * tr;
      v->aux[1] = c->c[1] * tr;
      v->aux[2] = c->c[2] * ds;
      v->aux[3] = c->c[3] * ds;
      v->aux[4] = c->c[4] * (0.4f + 1.2f * tn);
      v->aux[5] = c->c[9] * ds;
      if (c->c[5] > 0)
        svf_set(&v->s1, c->c[5] * tr, 1.5f, v->sr);
      env_set(v, 0, v->aux[2]);
      if (c->c[7] > 0) {
        env_set(v, 1, v->aux[5]);
      } else {
        env_set(v, 1, v->aux[3]);
        v->idrive = 1.0f / fm_tanhf(c->c[6]);
      }
      break;
    case K_CLAP:
      svf_set(&v->s1, c->c[0] * tone_scale(tn, 1.0f), c->c[1], v->sr);
      svf_set(&v->s2, c->c[7], 0.7f, v->sr);
      v->aux[0] = c->c[5] * ds;
      break;
    case K_NOISE:
      svf_set(&v->s1, c->c[0] * tone_scale(tn, 1.0f), 0.7f, v->sr);
      v->aux[0] = c->c[2] * ds;
      env_set(v, 0, c->c[1]);
      env_set(v, 1, v->aux[0]);
      break;
    default:
      break;
  }
}

static void sample_init(Voice* v, int semis) {
  v->smp = sample_get(v->machine, v->voice);
  v->pos = 0;
  float tr = fm_powf(2.0f, (v->p[P_TUNE] + semis) / 12.0f);
  v->step = (float)v->smp->rate / v->sr * tr;
  float d = v->p[P_DECAY];
  v->aux[0] = d >= 0.5f ? 0.0f : 0.02f * fm_powf(40.0f, d * 2.0f);  // decay tau, 0 = off
  v->tone_lp = 0;
  float t = v->p[P_TONE];
  v->aux[1] = t < 0.5f ? onepole_a(400.0f * fm_powf(50.0f, t * 2.0f), v->sr) : 0.0f;
  v->aux[2] = t > 0.5f ? (t - 0.5f) * 2.0f * 1.0f : 0.0f;  // shelf boost amount
  v->tone_a = onepole_a(3000.0f, v->sr);
}

// G.711 mu-law byte -> linear, filled once (every engine shares it).
static float g_ulaw[256];
static bool g_ulaw_ready;

static void ulaw_init(void) {
  for (int i = 0; i < 256; i++) {
    int u = ~i & 0xFF;
    int t = (((u & 0x0F) << 3) + 0x84) << ((u >> 4) & 7);
    t -= 0x84;
    g_ulaw[i] = (u & 0x80 ? -t : t) / 32768.0f;
  }
  g_ulaw_ready = true;
}

static inline float smp_at(const Sample* s, int32_t i) {
  if (i < 0 || (uint32_t)i >= s->frames)
    return 0.0f;
  return g_ulaw[s->data[i]];
}

static float tick_sample(Voice* v) {
  const Sample* s = v->smp;
  int32_t i = (int32_t)v->pos;
  float f = v->pos - (float)i;
  float a = smp_at(s, i - 1), b = smp_at(s, i), c = smp_at(s, i + 1), d = smp_at(s, i + 2);
  float x = b + 0.5f * f * (c - a + f * (2 * a - 5 * b + 4 * c - d + f * (3 * (b - c) + d - a)));
  v->pos += v->step;
  if (v->pos >= s->frames)
    v->active = false;
  if (v->aux[0] > 0)
    x *= fm_expf(-v->t / v->aux[0]);
  if (v->aux[1] > 0) {
    v->tone_lp += v->aux[1] * (x - v->tone_lp);
    x = v->tone_lp;
  } else if (v->aux[2] > 0) {
    v->lp2 += v->tone_a * (x - v->lp2);
    x += (x - v->lp2) * v->aux[2];
  }
  return x;
}

static float tick_swept(Voice* v) {
  float t = v->t;
  float f = v->f0 * (1.0f + v->famt * env(v, 0));
  v->ph[0] += f / v->sr;
  v->ph[0] -= fm_floorf(v->ph[0]);
  float e = env(v, 1);
  float x = fm_sinf(TAU * v->ph[0]) * e;
  float n = rnd(v);
  v->lp1 += v->ca * (n - v->lp1);
  x += v->lp1 * env(v, 2) * v->click;
  if (v->nbody > 0) {
    v->lp2 += 0.2f * (n - v->lp2);
    x += v->lp2 * e * e * v->nbody;
  }
  if (t > 0.01f && e < 0.0005f)
    v->active = false;
  return fm_tanhf(v->drive * x) * v->idrive;
}

static float tick_snare(Voice* v) {
  float t = v->t, dt = 1.0f / v->sr;
  const float* a = v->aux;
  float drop = v->cfg->c[4];
  float d = env(v, 0);
  float f1 = a[0] * (1.0f + drop * d);
  float f2 = a[1] * (1.0f + drop * d);
  v->ph[0] += f1 * dt;
  v->ph[1] += f2 * dt;
  v->ph[0] -= fm_floorf(v->ph[0]);
  v->ph[1] -= fm_floorf(v->ph[1]);
  float e1 = env(v, 1), e2 = env(v, 2);
  float body = fm_sinf(TAU * v->ph[0]) * e1 * 0.75f + fm_sinf(TAU * v->ph[1]) * e2 * 0.5f * a[6];
  float n = rnd(v), lp, bp, hp;
  svf_tick(&v->s1, n, &lp, &bp, &hp);
  v->lp1 += v->ca * (hp - v->lp1);
  float ne = env(v, 3);
  float x = body * 0.6f + v->lp1 * ne * a[5] * 0.5f;
  x += rnd(v) * env(v, 4) * v->cfg->c[9];
  if (t > 0.02f && e1 < 0.0005f && e2 < 0.0005f && ne < 0.0005f)
    v->active = false;
  return x;
}

static float tick_metal(Voice* v) {
  float t = v->t, dt = 1.0f / v->sr;
  float s = 0;
  for (int i = 0; i < 6; i++) {
    v->ph[i] += v->fr[i] * dt;
    v->ph[i] -= fm_floorf(v->ph[i]);
    s += square(v->ph[i], v->fr[i] * dt);
  }
  s /= 3.0f;
  float nf = v->cfg->c[6];
  float x = s * (1.0f - nf) + rnd(v) * nf * 0.8f;
  float lp, bp, hp, lp2, bp2, hp2;
  svf_tick(&v->s1, x, &lp, &bp, &hp);
  svf_tick(&v->s2, bp * 1.5f + x * 0.3f, &lp2, &bp2, &hp2);
  float e = (1.0f - v->aux[2]) * env(v, 0) + v->aux[2] * env(v, 1);
  float click = rnd(v) * env(v, 2) * v->cfg->c[7];
  if (t > 0.01f && e < 0.0003f)
    v->active = false;
  return (hp2 + click * 0.5f) * e;
}

static float tick_ping(Voice* v) {
  float t = v->t, dt = 1.0f / v->sr;
  const float* a = v->aux;
  bool sq = v->cfg->c[7] > 0;
  v->ph[0] += a[0] * dt;
  v->ph[1] += a[1] * dt;
  v->ph[0] -= fm_floorf(v->ph[0]);
  v->ph[1] -= fm_floorf(v->ph[1]);
  float x, e;
  if (sq) {
    x = square(v->ph[0], a[0] * dt) + square(v->ph[1], a[1] * dt) * a[4];
    float tm = v->cfg->c[8];
    e = (1.0f - tm) * env(v, 0) + tm * env(v, 1);
    float lp, bp, hp;
    svf_tick(&v->s1, x, &lp, &bp, &hp);
    x = bp * e;
  } else {
    float e1 = env(v, 0), e2 = env(v, 1);
    x = fm_sinf(TAU * v->ph[0]) * e1 + fm_sinf(TAU * v->ph[1]) * a[4] * e2;
    float dr = v->cfg->c[6];
    x = fm_tanhf(dr * x) * v->idrive;
    e = fm_maxf(e1, e2);
  }
  if (t > 0.005f && e < 0.0005f)
    v->active = false;
  return x;
}

static float tick_clap(Voice* v) {
  float t = v->t;
  const Cfg* c = v->cfg;
  float sp = c->c[2], nb = c->c[3], bt = c->c[4], tl = c->c[6];
  float e;
  if (t < nb * sp) {
    e = fm_expf(-pt_fmodf(t, sp) / bt);
  } else {
    float tt = t - nb * sp;
    e = fm_expf(-tt / bt) + tl * fm_expf(-tt / v->aux[0]);
  }
  float n = rnd(v), lp, bp, hp, lp2, bp2, hp2;
  svf_tick(&v->s1, n, &lp, &bp, &hp);
  svf_tick(&v->s2, bp, &lp2, &bp2, &hp2);
  if (t > nb * sp + 0.01f && e < 0.0005f)
    v->active = false;
  return hp2 * e;
}

static float tick_noise(Voice* v) {
  float t = v->t;
  float n = rnd(v), lp, bp, hp;
  svf_tick(&v->s1, n, &lp, &bp, &hp);
  float e0 = env(v, 0);
  float e = (1.0f - e0) * env(v, 1);
  if (t > 0.005f && e < 0.0005f)
    v->active = false;
  return hp * e;
}

static float voice_tick(Voice* v) {
  float x = 0;
  switch (v->cfg->kind) {
    case K_SWEPT:
      x = tick_swept(v);
      break;
    case K_SNARE:
      x = tick_snare(v);
      break;
    case K_METAL:
      x = tick_metal(v);
      break;
    case K_PING:
      x = tick_ping(v);
      break;
    case K_CLAP:
      x = tick_clap(v);
      break;
    case K_NOISE:
      x = tick_noise(v);
      break;
    case K_SAMPLE:
      x = tick_sample(v);
      break;
    default:
      v->active = false;
  }
  v->t += v->dt;
  if (v->choke > 0) {
    x *= v->choke / 0.004f;
    v->choke -= v->dt;
    if (v->choke <= 0)
      v->active = false;
  }
  return x * v->gain;
}

Engine* eng_create(float sr) {
  if (!g_ulaw_ready)
    ulaw_init();
  Engine* e;
  if (pt_used >= PT_POOL)
    return 0;
  e = &pt_pool[pt_used++];
  memset(e, 0, sizeof *e);
  e->sr = sr > 0 ? sr : 48000.0f;
  e->master = 1.0f;
  for (int v = 0; v < V_COUNT; v++) {
    e->vp[v][P_LEVEL] = 0.8f;
    e->vp[v][P_TUNE] = 0.0f;
    e->vp[v][P_DECAY] = 0.5f;
    e->vp[v][P_TONE] = 0.5f;
    e->vp[v][P_EXTRA] = 0.5f;
  }
  return e;
}

void eng_destroy(Engine* e) { (void)e; }   /* (the pool's: kept) */

void eng_reset(Engine* e) {
  for (int v = 0; v < V_COUNT; v++) e->voices[v].active = false;
}

void eng_trigger(Engine* e, int machine, int voice, int semis, float vel) {
  if (!eng_machine_has(machine, voice))
    return;
  Voice* v = &e->voices[voice];
  memset(v, 0, sizeof *v);
  v->machine = machine;
  v->voice = voice;
  v->cfg = cfg_for(machine, voice);
  v->sr = e->sr;
  v->dt = 1.0f / e->sr;
  memcpy(v->p, e->vp[voice], sizeof v->p);
  v->vel = vel;
  float k = 1.0f;
  if (!trommelsynthesizer_raw_gain)
    k = K_GAIN[machine][voice];
  v->gain = e->master * v->p[P_LEVEL] * vel * k;
  if (v->cfg->kind == K_SAMPLE)
    sample_init(v, semis);
  else
    voice_init(v, semis);
  v->active = true;
  // Closed hat chokes the open hat, as on the real machines.
  if (voice == V_CH && e->voices[V_OH].active && e->voices[V_OH].choke <= 0)
    e->voices[V_OH].choke = 0.004f;
}

void eng_note_on(Engine* e, int key, float vel) {
  int v, s;
  if (eng_gm_lookup(e->machine, key, &v, &s))
    eng_trigger(e, e->machine, v, s, vel);
}

static inline float softclip(float x) {
  float a = fm_fabsf(x);
  if (a <= 0.8f)
    return x;
  float y = 0.8f + 0.2f * fm_tanhf((a - 0.8f) / 0.2f);
  return x < 0 ? -y : y;
}

void eng_render(Engine* e, float* l, float* r, uint32_t n) {
  uint32_t i;
  for (i = 0; i < n; i++) l[i] = 0.0f;
  for (int v = 0; v < V_COUNT; v++)  // (a voice ending mid-block adds nothing after: as voice by voice a sample)
    for (i = 0; i < n && e->voices[v].active; i++) l[i] += voice_tick(&e->voices[v]);
  for (i = 0; i < n; i++) l[i] = r[i] = trommelsynthesizer_raw_gain ? l[i] : softclip(l[i]);
}

// ---- params ----------------------------------------------------------------

void eng_set_param(Engine* e, uint32_t id, float value) {
  if (id == PID_MACHINE) {
    int m = (int)(value + 0.5f);
    e->machine = m < 0 ? 0 : (m >= M_COUNT ? M_COUNT - 1 : m);
  } else if (id == PID_MASTER) {
    e->master = (float)value;
  } else if (id < PID_COUNT) {
    uint32_t k = id - 2;
    e->vp[k / P_COUNT][k % P_COUNT] = (float)value;
  }
}

float eng_get_param(const Engine* e, uint32_t id) {
  if (id == PID_MACHINE)
    return e->machine;
  if (id == PID_MASTER)
    return e->master;
  if (id < PID_COUNT) {
    uint32_t k = id - 2;
    return e->vp[k / P_COUNT][k % P_COUNT];
  }
  return 0;
}


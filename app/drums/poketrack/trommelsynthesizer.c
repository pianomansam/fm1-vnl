typedef struct {
  bool active;
  int machine, voice;
  const Cfg* cfg;
  float t, dt, sr;
  float gain, vel;
  float choke;  // >0: ramping out, seconds left
  float p[P_COUNT];
  // working constants, set at trigger
  float f0, famt, ftau, atau, click, drive, nbody;
  float ph[6], fr[6];
  float aux[8];
  Svf s1, s2, s3;
  float lp1, lp2, ca;
  float ev[5], ek[5];  // envelopes exp(-t / tau): the value now, its factor a sample (env_set, env)
  float idrive;        // 1 / tanh(drive)
  uint32_t rng;
  // samples
  const Sample* smp;
  float pos, step;
  float tone_lp, tone_a;
} Voice;

struct Engine {
  float sr;
  int machine;
  float master;
  float vp[V_COUNT][P_COUNT];
  Voice voices[V_COUNT];
};


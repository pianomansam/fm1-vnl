RUNTIME_SOURCES = {"maps", "progs", "families", None}
# Rows the screens name that rows.json lacks (the page builds them): rhythm, the Comp part's one Rhythm row (comp or
# strumPat by fits.rhythmRow: ch_rhythm_row), and loop (the workbench's Loop section switch)
VIRTUAL = ["rhythm", "loop", "endless"]
ST = {"approved": 0, "candidate": 1, "retired": 2, "removed": 3}
CH_HIDDEN, CH_ROLLED = 4, 8
FAM = {None: 0, "acoustic": 1, "synth": 2, "electric": 3, "any": 4}   # CH_FAM: an instrument's or kit's family


def choices(row, opts):
    """the row's every choice, as rows.js's allOptions (unfiltered: the device filters retired, hidden and unfitting
       ones as optionsFor does): [(value, NAME, status, flags, keys or None, notKeys)]. Names as the device writes
       them: upper case, a bass's short name. A kick phrase's value is its place (0 the pattern's own, 1.. the
       options.json kickPhrases in order), the C side having no strings for values."""
    src = row.get("source")
    def lst(names, start=0):
        return [(i + start, n) for i, n in enumerate(names)]
    def rng(lo, hi, step, fmt):
        return [(v, fmt(v)) for v in range(lo, hi + 1, step)]
    rolled = (-1, "AS ROLLED", 0, CH_ROLLED)
    out = []
    plain = None
    if src == "keys":
        plain = lst(["C", "Db", "D", "Eb", "E", "F", "F#", "G", "Ab", "A", "Bb", "B"])
    elif src == "modes":
        plain = lst(["Ionian", "Dorian", "Phrygian", "Lydian", "Mixolydian", "Aeolian"])
    elif src == "tempo":
        plain = rng(70, 90, 1, lambda t: f"{t} BPM")
    elif src == "swing":
        plain = rng(520, 620, 1, lambda s: f"{s / 10:.1f}%")
    elif src == "moods":
        plain = lst(["Sad", "Wistful", "Warm", "Sunny"])
    elif src == "motion":
        plain = rng(0, 100, 5, str)
    elif src == "colors":
        plain = lst(["7ths", "9ths", "Rich (9/11/13)"])
    elif src == "dust":
        plain = lst(["None", "Light", "Medium", "Heavy"])
    elif src == "noise":
        plain = lst(["None", "Vinyl", "Tape"])
    elif src == "ambience":
        plain = lst(["None", "Rain"])
    elif src == "offOn":
        plain = lst(["Off", "On"])
    if plain is not None:
        return [(v, n.upper(), 0, 0, None, None) for v, n in plain]
    if src == "instruments":
        role = {"CHORD": "keys", "LEAD": "lead", "BASS": "bass", "PAD": "pad"}[row["role"]]
        return [(i["id"], ((row["role"] == "BASS" and i.get("short")) or i["name"]).upper(), ST[i["status"]],
                 FAM[i.get("family")] << 4, None, None) for i in opts["instruments"] if role in i["roles"]]
    if src == "comping":
        out.append(rolled + (None, None))
        rhythms = [dict(c, id=c["value"]) for c in opts.get("compRhythms", [])]
        for c in rhythms + opts["comping"]:
            out.append((c["id"], c["name"].upper(), ST[c["status"]], CH_HIDDEN if c.get("sym") == "CS_PAT" else 0,
                        c.get("keys"), c.get("notKeys")))
        return [(v, n.upper(), s, f, k, nk) for v, n, s, f, k, nk in out]
    if src == "leadStyles":
        return [rolled + (None, None)] + [(s["id"], s["name"].upper(), ST[s["status"]], 0, None, None)
                                          for s in opts["leadStyles"]]
    if src == "registers":
        return [(-1, "DOWN AN OCTAVE", 0, 0, None, None), (0, "AS ROLLED", 0, CH_ROLLED, None, None),
                (1, "UP AN OCTAVE", 0, 0, None, None)]
    def with_rolled(names, first="As rolled"):
        return [(-1, first.upper(), 0, CH_ROLLED, None, None)] + [(i, n.upper(), 0, 0, None, None)
                                                                 for i, n in enumerate(names)]
    if src == "leadLoop":
        return with_rolled(["Off", "On"], "Default")
    if src == "padOn":
        return with_rolled(["Off", "On"])
    if src == "onOffInverted":
        return [(0, "ON", 0, 0, None, None), (1, "OFF", 0, 0, None, None)]
    if src == "padPlaces":
        return with_rolled(["Below the lead", "With the lead", "Above the lead"])
    if src == "rides":
        return with_rolled(["None", "Throughout", "One section"])
    if src == "strumFills":
        return with_rolled(["Step back", "Drive"], "Default")
    if src == "kits":
        return [(k["id"], (k.get("short") or k["name"]).upper(), ST[k["status"]], FAM[k.get("family")] << 4, None, None)
                for k in opts["kits"]]
    if src == "patterns":
        return [(p["id"], p["name"].upper(), ST[p["status"]], 0, None, None) for p in opts["patterns"]]
    if src == "strumPats":
        return [rolled + (None, None)] + [(p["index"], p["name"].upper(), ST[p["status"]], 0, None, None)
                                          for p in opts["strumPats"]]
    if src == "kickPhrases":
        return [(0, "THE PATTERN'S OWN", 0, 0, None, None)] + [
            (i + 1, (k.get("name") or "KICK " + k["id"].lstrip("kK")).upper(), ST[k.get("status", "approved")], 0, None, None)
            for i, k in enumerate(opts["kickPhrases"])]
    if src in RUNTIME_SOURCES:
        return []
    raise Refused(f"rows.json: row {row['id']}: no choices for source {src}")


def mask(ids, what):
    m = 0
    for i in ids:
        if not 0 <= i < 32:
            raise Refused(f"{what}: instrument {i} doesn't fit a 32-bit mask")
        m |= 1 << i
    return m


def shown_rows(data):
    """the rows whose choices a screen names: an options field's row, and a row a template or condition reads
       ({kit}, {rhythm}Pend); the rhythm row's names are its comp's and strumPat's"""
    out = {d["row"] for d in data["fields"].values() if d.get("options")}
    fields, named = set(data["fields"]) | set(data.get("lines", {})), set()
    def walk(x, key=None):
        if isinstance(x, dict):
            for k, v in x.items():
                walk(v, k)
        elif isinstance(x, list):
            for v in x:
                walk(v, key)
        elif isinstance(x, str):
            named.update(re.findall(r"\{(\w+?)(?:Pend)?\}", x))   # a template's values
            if key in ("when", "value"):                             # a condition's, a meter's
                named.add(re.sub(r"^!|Pend$", "", x))
    walk(data)
    out |= named - fields   # (a name that is a field's too reads the field: its row isn't named)
    if "rhythm" in out:
        out |= {"comp", "strumPat"}
    return out


def song_row(r):
    """the song's request on a row (song.h's song_request_row): SR_ROLL + RF_*, SR_ROLE + V_*, SR_OV + OV_*, SR_KIT;
       -1 where the song takes none (the seed, the family, the screens' own rows, a kick phrase: not on the device yet)"""
    kind = r.get("kind")
    if kind == "roll":
        return f"SR_ROLL + RF_{r['field']}"
    if kind == "role":
        return f"SR_ROLE + V_{r['role']}"
    if kind in ("ov", "reroll"):
        return f"SR_OV + OV_{r['key']}"
    if kind == "drum":
        return {"kit": "SR_KIT", "pattern": "SR_ROLL + RF_PATTERN"}.get(r.get("key"), "-1")
    return "-1"


def gen_choices(rows, opts, shown):
    rows = rows["rows"] + [{"id": "rhythm", "kind": "virtual"}, {"id": "loop", "kind": "virtual", "source": "offOn"},
                            {"id": "endless", "kind": "virtual", "source": "offOn"}]
    fits = json.loads((WB / "rows.json").read_text())["fits"]
    s = Strings()
    entries, spans, fit_rows = [], [], []
    for r in rows:
        cs = choices(r, opts) if r["id"] in shown and r.get("source") != "swing" else []   # (a row no screen names:
        # no table, no flash; the swing's 101 names are written, not stored: ch_name)
        spans.append((len(entries), len(cs)))
        for v, n, st, fl, keys, nkeys in cs:
            if not -128 <= v <= 127:
                raise Refused(f"rows.json: row {r['id']}: value {v} doesn't fit a byte (ch_entry_t)")
            entries.append((v, s(n), st | fl, keys, nkeys))
    if len(entries) > 255:
        raise Refused(f"{len(entries)} choices: more than CH_SPAN's bytes hold")
    kof, nkof = fits["comping"]["keysOf"], fits["comping"]["notKeysOf"]
    assert (kof, nkof) == ("keys", "notKeys"), "choices(): reads comping's keys and notKeys"
    comp_row = next(i for i, r in enumerate(rows) if r.get("source") == "comping")
    strum = next(c for c in opts["comping"] if c["sym"] == fits["rhythmRow"]["strumSym"])
    ids = {r["id"]: i for i, r in enumerate(rows)}
    first, n = spans[comp_row]
    fit_masks = [(mask(e[3], "comping") if e[3] is not None else 0xFFFFFFFF, mask(e[4] or [], "comping"))
                 for e in entries[first:first + n]]
    h = [HEAD, "#ifndef UI_CHOICES_GEN_H\n#define UI_CHOICES_GEN_H\n#include <stdint.h>\n\n",
         "/* The rows, in workbench/rows.json's order, then the screens' own (rhythm: the Comp part's one Rhythm row, comp\n"
         "   or strumPat as ch_rhythm_row says; loop: the Loop section switch). A row's value is the workbench's (a kick\n"
         "   phrase's: 0 the pattern's own, 1.. options.json's kickPhrases in order). Rows with no table here (seed,\n"
         "   map, prog, family, the re-rolls, and any row no screen names): ch_count 0, ch_name NULL; the engine's\n"
         "   library or a number names them. */\n",
         "enum {\n" + "".join(f"    ROW_{ident(r['id'])},\n" for r in rows) + "    ROW_N\n};\n\n",
         "/* a choice's flags (ch_flags): its status in the low 2 bits (0 approved, 1 candidate, 2 retired: behind\n"
         "   \"show retired\", 3 removed: never offered), CH_HIDDEN never offered itself (shown as the current value\n"
         "   only), CH_ROLLED the engine's own choice (\"as rolled\"), CH_FAM an instrument's or kit's family (0 none,\n"
         "   CH_ACOUSTIC, CH_SYNTH, CH_ELECTRIC, CH_ANY: options.json's) */\n"
         "#define CH_STATUS(f) ((f) & 3)\n#define CH_HIDDEN 4\n#define CH_ROLLED 8\n#define CH_FAM(f) ((f) >> 4 & 7)\n"
         "enum { CH_ACOUSTIC = 1, CH_SYNTH, CH_ELECTRIC, CH_ANY };\n\n",
         "const char *ch_name(int row, int value);          /* its name as the device writes it; NULL: no such choice */\n",
         "int ch_count(int row);                            /* its choices, in the workbench's order */\n",
         "int ch_value(int row, int index);\n",
         "int ch_flags(int row, int value);                 /* -1: no such choice */\n",
         "int ch_is_retired(int row, int value);            /* retired or removed */\n",
         "/* a choice fits the comp instrument keys_ins: a comping style (ROW_COMP) iff (!keys || keys contains it) and\n"
         "   !(notKeys contains it) (rows.json's fits.comping); every other row's always */\n",
         "int ch_fits(int row, int value, int keys_ins);\n",
         "/* rows.js's rhythmRow: ROW_STRUM_PAT when the strum style fits keys_ins and comp (a ROW_COMP value) is as\n"
         "   rolled, strum or a style that fits; else ROW_COMP */\n",
         "int ch_rhythm_row(int keys_ins, int comp);\n",
         "/* each row's request on the song (song.h's song_request_row: SR_ROLL + RF_*, SR_ROLE + V_*, SR_OV + OV_*,\n"
         "   SR_KIT), -1 where it takes none. The comp row's value is the workbench's: a comp rhythm (from 100) is the\n"
         "   COMP_PAT override, anything else COMP */\n",
         "extern const int8_t CH_SONG_ROW[ROW_N];\n"
         "extern const char *const CH_ROW_ID[ROW_N];      /* each row's id (rows.json's: the live state) */\n\n#endif\n"]
    c = [HEAD, '#include "choices_gen.h"\n#include "song.h"\n\n', s.c("CH_STR"), "\n",
         "const int8_t CH_SONG_ROW[ROW_N] = {\n" + "".join(f"    {song_row(r)},   /* {r['id']} */\n" for r in rows) + "};\n",
         "const char *const CH_ROW_ID[ROW_N] = {" + ", ".join(f'"{r["id"]}"' for r in rows) + "};\n",
         "typedef struct { int8_t value; uint8_t flags; uint16_t name; } ch_entry_t;   /* 4 bytes */\n",
         f"static const ch_entry_t CH_E[{len(entries)}] = {{\n" +
         "".join(f"    {{{v}, {fl}, {nm}}},\n" for v, nm, fl, _, _ in entries) + "};\n",
         f"static const uint8_t CH_SPAN[ROW_N][2] = {{\n" + "".join(f"    {{{a}, {b}}},   /* {r['id']} */\n"
                                                                for (a, b), r in zip(spans, rows)) + "};\n",
         f"static const uint32_t CH_COMP_FIT[{max(1, n)}][2] = {{\n" +
         "".join(f"    {{{a}u, {b}u}},\n" for a, b in fit_masks) + "};\n\n",
         "static int find(int row, int value) {\n"
         "    if (row < 0 || row >= ROW_N) return -1;\n"
         "    for (int i = 0; i < CH_SPAN[row][1]; i++)\n"
         "        if (CH_E[CH_SPAN[row][0] + i].value == value) return CH_SPAN[row][0] + i;\n"
         "    return -1;\n}\n\n"
         "/* the swing: per mille 520..620, named \"52.0%\" (rows.js's), written rather than stored */\n"
         "#define CH_SWING_LO 520\n#define CH_SWING_HI 620\n"
         "static int is_swing(int row, int v) { return row == ROW_SWING && v >= CH_SWING_LO && v <= CH_SWING_HI; }\n"
         "const char *ch_name(int row, int value)\n{\n"
         "    static char t[8];\n"
         "    int i;\n"
         "    if (is_swing(row, value)) {\n"
         "        t[0] = (char)('0' + value / 100); t[1] = (char)('0' + value / 10 % 10); t[2] = '.';\n"
         "        t[3] = (char)('0' + value % 10); t[4] = '%'; t[5] = 0;\n"
         "        return t;\n"
         "    }\n"
         "    i = find(row, value);\n"
         "    return i < 0 ? 0 : CH_STR + CH_E[i].name;\n}\n"
         "int ch_count(int row)\n{\n"
         "    if (row == ROW_SWING) return CH_SWING_HI - CH_SWING_LO + 1;\n"
         "    return row < 0 || row >= ROW_N ? 0 : CH_SPAN[row][1];\n}\n"
         "int ch_value(int row, int index) { return row == ROW_SWING ? CH_SWING_LO + index : CH_E[CH_SPAN[row][0] + index].value; }\n"
         "int ch_flags(int row, int value)\n{\n"
         "    int i;\n"
         "    if (is_swing(row, value)) return 0;\n"
         "    i = find(row, value);\n"
         "    return i < 0 ? -1 : CH_E[i].flags;\n}\n"
         "int ch_is_retired(int row, int value) { int f = ch_flags(row, value); return f >= 0 && CH_STATUS(f) >= 2; }\n\n"
         "int ch_fits(int row, int value, int keys_ins) {\n"
         f"    if (row != ROW_{ident(rows[comp_row]['id'])} || keys_ins < 0 || keys_ins >= 32) return 1;\n"
         "    int i = find(row, value);\n"
         "    if (i < 0) return 1;\n"
         "    i -= CH_SPAN[row][0];\n"
         "    return ((CH_COMP_FIT[i][0] >> keys_ins) & 1u) && !((CH_COMP_FIT[i][1] >> keys_ins) & 1u);\n}\n\n"
         "int ch_rhythm_row(int keys_ins, int comp) {\n"
         f"    const int comp_row = ROW_{ident(rows[comp_row]['id'])}, strum = {strum['id']};\n"
         f"    if (!ch_fits(comp_row, strum, keys_ins)) return ROW_{ident(fits['rhythmRow']['compRow'])};\n"
         "    if (comp >= 0 && find(comp_row, comp) >= 0 && comp != strum && !ch_fits(comp_row, comp, keys_ins))\n"
         f"        return ROW_{ident(fits['rhythmRow']['compRow'])};\n"
         f"    return ROW_{ident(fits['rhythmRow']['strumRow'])};\n}}\n"]
    assert fits["rhythmRow"]["compRow"] in ids and fits["rhythmRow"]["strumRow"] in ids
    return "".join(h), "".join(c), rows


# ------------------------------------------------------------------------------------------------- the screens ---
# the engine's parts, in its order (voices.h's VX_PART_*: the mixer's levels): ui_part numbers them so, whatever order
# the screens show them in
ENGINE_PARTS = ["drums", "bass", "keys", "pad", "lead", "texture"]


def part_names(data):
    """every part the screens name: the engine's first, in its order (VX_PART_*), then any other as it appears"""
    out = list(ENGINE_PARTS)
    def walk(x, key=None):
        if isinstance(x, dict):
            for k, v in x.items():
                walk(v, k)
        elif isinstance(x, list):
            for v in x:
                walk(v, key)
        elif isinstance(x, str) and key in ("parts", "lanes", "part") and x not in out:
            out.append(x)
    walk(data["screens"])
    walk(data.get("defaults", {}))
    walk(data.get("keyLeds", {}))
    return out


def gen_screens(data, vocab, rows, all_parts=None):
    errs = []
    row_ids = [r["id"] for r in rows]                              # choices_gen.h's rows (rows.json's, the virtual ones)
    value_rows = [r["id"] for r in rows if r.get("kind") != "virtual"]   # {row}: rows.json's (device.js's valueNames)
    fields = list(data["fields"])
    lines = list(data.get("lines", {}))
    fonts = font_names()
    used_fonts = set()
    theme = theme_colors()
    colors = list(THEME) + list(data.get("colors", {}))
    color_val = [theme[k] for k in THEME] + [rgb565(*v) for v in data.get("colors", {}).values()]
    screens = list(data["screens"])
    icons = list(data.get("icons", {}))
    kinds, akinds = list(vocab["items"]), list(vocab["actions"])
    s = Strings()

    # the values: fixed ones, then each pattern's family ({a-b}, {field}, {row}, {line}), members in vocab order
    values, groups = list(vocab["values"]["fixed"]), {}
    subs = {"field": fields, "row": value_rows, "line": lines}
    for p in vocab["values"]["patterns"]:
        m = re.search(r"\{(\d+)-(\d+)\}|\{(field|row|line)\}", p)
        key = m.group(0)
        groups.setdefault(key, []).append(p)
    group_info = []   # (C name, first id, members [(member C name, pattern)], items)
    for key, pats in groups.items():
        m = re.fullmatch(r"\{(\d+)-(\d+)\}|\{(field|row|line)\}", key)
        items = subs[m.group(3)] if m.group(3) else [str(i) for i in range(int(m.group(1)), int(m.group(2)) + 1)]
        cname = ident(m.group(3)) if m.group(3) else "I"
        first = len(values) + 1
        for x in items:
            for p in pats:
                values.append(p.replace(key, x))
        members = [(ident(p.replace(key, "_")).strip("_") or "VALUE", p) for p in pats]
        group_info.append((cname, first, members, items))
    # 0: none. A name in two families (a field and a row both "key") is the first's, as the mock's bag lets the field's
    # value stand over the row's label; the later slot stays (the UV_* arithmetic), unread
    vid = {}
    for i, v in enumerate(values):
        vid.setdefault(v, i + 1)
    if len(values) >= 1 << 14:
        raise Refused("too many values for a template's 14-bit ids")

    def tpl(where, t):
        out, at = bytearray(), 0
        for m in re.finditer(r"\{(\w+)\}", t):
            out += t[at:m.start()].encode("utf-8")
            if m.group(1) not in vid:
                errs.append(f"{where}: no value {{{m.group(1)}}}")
                continue
            i = vid[m.group(1)]
            out += bytes([1, 0x80 | (i & 0x7F), 0x80 | (i >> 7)])
            at = m.end()
        out += t[at:].encode("utf-8")
        return s(bytes(out))

    whens = [()]
    def when(where, w):
        xs = [w] if isinstance(w, str) else list(w or [])
        if len(xs) > 3:
            errs.append(f"{where}: more than 3 conditions")
        ids = []
        for x in xs:
            name = x.lstrip("!")
            if name not in vid:
                errs.append(f'{where}: no value "{x}"')
                continue
            ids.append(-vid[name] if x.startswith("!") else vid[name])
        t = tuple(ids)
        if t not in whens:
            whens.append(t)
        return whens.index(t)

    def color(where, c):
        if c not in colors:
            errs.append(f"{where}: no color {c}")
            return 0
        return colors.index(c)

    def font(where, f):
        used_fonts.add(f)
        if f not in fonts:
            errs.append(f"{where}: no font {f}")
            return 0
        return fonts.index(f)

    # lists of bytes (menus, pages, lanes, a byCursor's fields, keys): one table, an index each (0: the empty list)
    lists = [()]
    def lst(xs):
        t = tuple(xs)
        if t not in lists:
            lists.append(t)
        return lists.index(t)

    parts = list(all_parts or [])       # (the same numbering for the device's tables as the simulator's)
    def part(p):
        if p not in parts:
            parts.append(p)
        return parts.index(p)

    def field(where, f):
        if f not in fields:
            errs.append(f'{where}: no field "{f}"')
            return 0
        return fields.index(f)

    actions = [None]
    def action(where, a):
        if a is None:
            return 0
        kind = "go" if "go" in a else a.get("do")
        if kind not in vocab["actions"]:
            errs.append(f"{where}: unknown action {kind if kind is not None else json.dumps(a)}")
            return 0
        for k in a:
            if k != "do" and k not in vocab["actions"][kind]:
                errs.append(f"{where}: {kind} has no key {k}")
        arg, by, lng, lis = -1, 0, 0, 0
        if kind == "go":
            if a["go"] in GO_SPECIAL:
                arg = GO_SPECIAL[a["go"]]
            elif a["go"] in screens:
                arg = screens.index(a["go"])
            else:
                errs.append(f'{where}: no screen "{a["go"]}"')
        elif kind in ("turn", "nudge"):
            if a.get("byCursor") is not None:
                lis = lst(NONE8 if f is None else field(where, f) for f in a["byCursor"])
            else:
                arg = field(where, a.get("field"))
            by = a.get("by", 0) if kind == "nudge" else a.get("step", 1)
        elif kind == "jump":
            arg = a.get("i", -1)
        elif "part" in a:
            arg = part(a["part"])
        if a.get("long"):
            lng = action(f"{where}.long", a["long"])
        t = (akinds.index(kind) + 1, arg & 0xFF if arg >= 0 else NONE8, by, lng, lis)
        if t not in actions:
            actions.append(t)
        return actions.index(t)

    items, bands, says, knob_styles, lane_items, keyleds, lones = [], [], [], [], [], [], []
    band_at = {}

    def item(where, it):
        kind = next((k for k in kinds if k in it), None)
        if kind is None:
            errs.append(f"{where}: no draw item {next((k for k in it if k != 'when'), '(empty)')}")
            return None
        for k in it:
            if k not in vocab["items"][kind]:
                errs.append(f"{where}: {kind} has no key {k}")
        x = y = w = h = 0
        fnt = col = back = past = arrows = 0
        pos, ref, arrows_right = 0, 0, 232
        if kind == "text":
            fnt, col, ref = font(where, it.get("font")), color(where, it.get("color")), tpl(where, it["text"])
            y = it.get("y", 0)
            if "right" in it:
                pos, x = 1, it["right"]
            elif "after" in it:
                pos, x = 2, it["after"]
            else:
                x = it.get("x", 0)
            if it.get("arrows"):
                arrows = 1 + color(where, "DIM" if it["arrows"] is True else it["arrows"])
                arrows_right = it.get("arrowsRight", 232)
            lone = re.fullmatch(r"\{(\w+)\}", it["text"])   # a value alone: its Pend (the pending color), First, Last
            if lone:
                lt = tuple(vid.get(lone.group(1) + x, 0) for x in ("Pend", "First", "Last")) + \
                    ((it.get("arrowsRight", 232) if it.get("arrows") else 0), arrows)
                if lt not in lones:
                    lones.append(lt)
                past = 1 + lones.index(lt)
        elif kind == "icon":
            if it["icon"] not in icons:
                errs.append(f"{where}: no icon {it['icon']}")
            else:
                ref = icons.index(it["icon"])
            x, y, col = it["x"], it["y"], color(where, it["color"])
        else:
            geo = it[kind]
            if kind == "knobs":
                k = it["knobs"]
                ks = (k["x"], k["dx"], k["label"]["y"], font(where, k["label"]["font"]), color(where, k["label"]["color"]),
                      k["value"]["y"], font(where, k["value"]["font"]), color(where, k["value"]["color"]),
                      when(where, k["value"].get("when")),
                      *((k["bar"]["y"], k["bar"]["w"], k["bar"]["h"], color(where, k["bar"]["color"]),
                         color(where, k["bar"]["back"])) if "bar" in k else (0, 0, 0, 0, 0)))
                if ks not in knob_styles:
                    knob_styles.append(ks)
                ref = knob_styles.index(ks)
            else:
                x, y, w, h = geo
            if kind in ("rect", "meter", "sections"):
                col = color(where, it["color"])
            if kind in ("meter", "sections") and "back" in it:
                back = color(where, it["back"])
            if kind == "sections":
                past = color(where, it["past"])
            if kind == "meter":
                if it["value"] not in vid:
                    errs.append(f'{where}: no value "{it["value"]}"')
                else:
                    ref = vid[it["value"]]
                fd = data["fields"].get(re.sub(r"Frac$", "", it["value"]))
                if fd and (fd.get("options") or fd.get("format") or fd.get("wrap")):
                    past = 1                                    # a field's bar: numbers only (device.js's hasBar)
            if kind in ("lanes", "faders"):
                lt = (lst(part(p) for p in it["parts"]), it.get("label", 52), it.get("rowH", 22), it.get("window", 8),
                      s("|".join(it.get("keys", it.get("labels", [])))), s("|".join(it.get("tags", []))),
                      1 if it.get("live") else 0)
                if lt not in lane_items:
                    lane_items.append(lt)
                ref = lane_items.index(lt)
        for v in (x, y, w, h, arrows_right):
            if not 0 <= v <= 255:
                errs.append(f"{where}: {v} doesn't fit a byte")
        if col > 15 or back > 15 or fnt > 7 or len(kinds) > 8:
            errs.append(f"{where}: more colors, faces or kinds than an item packs")
        return (kinds.index(kind), fnt, pos, col, back, x & 0xFF, y & 0xFF, w & 0xFF, h & 0xFF,
                when(where, it.get("when")), past, ref)

    def band(where, b):
        its = [item(where, it) for it in b.get("draw", [])]
        its = tuple(i for i in its if i is not None)
        if its not in band_at:
            band_at[its] = len(items)
            items.extend(its)
        bt = (b["y"], b["h"], color(where, b.get("bg", "BLACK")), band_at[its], len(its))
        if not (0 <= b["y"] and b["h"] > 0 and b["y"] + b["h"] <= 240):
            errs.append(f"{where}: outside the screen (y {b['y']}, h {b['h']})")
        return bt

    def key_leds(where, k):
        if not k:
            return 0
        kl = (1 if "lanes" in k else 2, lst(k.get("lanes", k.get("sections", []))), lst(part(p) for p in k.get("parts", [])))
        if kl not in keyleds:
            keyleds.append(kl)
        return len(keyleds)   # 0: none

    for c, a in data.get("defaults", {}).items():
        if c not in CONTROLS:
            errs.append(f"defaults: no control {c}")
        action(f"defaults.{c}", a)
    default_kl = key_leds("keyLeds", data.get("keyLeds"))
    for p in data.get("parts", []):
        if p not in screens:
            errs.append(f'parts: no screen "{p}"')
    scr = []
    for sid, sc in data["screens"].items():
        b0 = len(bands)
        for i, b in enumerate(sc.get("bands", [])):
            bands.append(band(f"{sid}.bands[{i}]", b))
        knobs = []
        for k in range(4):
            kn = (sc.get("knobs") or [])[k] if k < len(sc.get("knobs") or []) else None
            knobs.append((field(f"{sid}.knobs", kn["field"]), kn.get("step", 1)) if kn else (NONE8, 0))
        if len(sc.get("knobs") or []) > 4:
            errs.append(f"{sid}: more than four knobs")
        own = sc.get("controls", {})
        for c in own:
            if c not in CONTROLS:
                errs.append(f"{sid}.controls: no control {c}")
        ctl = []
        for c in CONTROLS:   # device.js's actionOf: the screen's own, a knob's turn, else the defaults'
            if c in own:
                ctl.append(action(f"{sid}.controls.{c}", own[c]))
            elif c in KNOBS:
                k = KNOBS.index(c)
                kn = (sc.get("knobs") or [None] * 4)[k] if k < len(sc.get("knobs") or []) else None
                ctl.append(action(f"{sid}.knobs", {"do": "turn", "field": kn["field"], "step": kn.get("step", 1)})
                           if kn else 0)
            else:
                ctl.append(action(f"defaults.{c}", data.get("defaults", {}).get(c)))
        say0 = len(says)
        for p in sc.get("say", []):
            says.append((tpl(f"{sid}.say", p), 0) if isinstance(p, str) else
                        (tpl(f"{sid}.say", p["text"]), when(f"{sid}.say", p.get("when"))))
        for m in sc.get("menu", []) + sc.get("pages", []):
            if m not in screens:
                errs.append(f'{sid}: no screen "{m}"')
        scr.append(dict(title=s(sc.get("title", sid)), bands=b0, n_bands=len(bands) - b0, knobs=knobs, controls=ctl,
                        menu=lst(screens.index(m) for m in sc.get("menu", []) if m in screens),
                        pages=lst(screens.index(m) for m in sc.get("pages", []) if m in screens),
                        lanes=lst(part(p) for p in sc.get("lanes", [])),
                        list=1 if sc.get("list") == "sections" else 0,
                        key_leds=key_leds(f"{sid}.keyLeds", sc.get("keyLeds")) or default_kl,
                        say=say0, n_say=len(says) - say0, placeholder=1 if sc.get("placeholder") else 0, rows=sc.get("rows", 0)))
    line_tpl = [tpl(f"lines.{k}", t) for k, t in data.get("lines", {}).items()]
    part_screens = lst(screens.index(p) for p in data.get("parts", []) if p in screens)
    if data["home"] not in screens:
        errs.append(f'home "{data["home"]}" is not a screen')
    if errs:
        raise Refused("\n".join(errs))

    # icons: 9-px rows, bit i the column i from the left
    icon_rows = []
    for name in icons:
        rws = data["icons"][name]
        if len(rws) > 8 or any(len(r) > 9 for r in rws):
            raise Refused(f"icons.{name}: more than 8 rows of 9")
        icon_rows.append([sum(1 << i for i, ch in enumerate(r) if ch == "#") for r in rws])
    list_off, flat = [], []
    for L in lists:
        list_off.append((len(flat), len(L)))
        flat.extend(L)

    # every index must fit the field it is written to
    for what, n, lim in (("bands", len(bands), 256), ("items", len(items), 1 << 16), ("conditions", len(whens), 256),
                         ("actions", len(actions), 256), ("lists", len(lists), 256), ("list bytes", len(flat), 1 << 16),
                         ("knob styles", len(knob_styles), 1 << 16), ("lane items", len(lane_items), 1 << 16),
                         ("key lights", len(keyleds) + 1, 256), ("says", len(says), 256), ("strings", len(s.buf), 1 << 16),
                         ("screens", len(screens), min(GO_SPECIAL.values())), ("fields", len(fields), NONE8),
                         ("parts", len(parts), NONE8)):
        if n > lim:
            raise Refused(f"too many {what} ({n}) for the tables' {lim}")
    if any(b[4] > 255 for b in bands):
        raise Refused("a band with more than 255 items")


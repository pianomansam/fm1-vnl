class Refused(Exception):
    pass


def ident(s):
    """a C identifier's upper-case part from a name: keysOct -> KEYS_OCT, OCT- -> OCT_MINUS"""
    s = s.replace("-", "_MINUS").replace("+", "_PLUS")
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", s).upper()


def rgb565(r, g, b):
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


class Strings:
    """one table of NUL-ended strings, each kept once: an id is its offset"""
    def __init__(self):
        self.buf, self.at = bytearray(), {}

    def __call__(self, s):
        b = s.encode("utf-8") if isinstance(s, str) else bytes(s)
        if b not in self.at:
            self.at[b] = len(self.buf)
            self.buf += b + b"\0"
        return self.at[b]

    def c(self, name):
        lines, cur = [], bytearray()
        for b in self.buf:
            cur.append(b)
            if b == 0 or len(cur) >= 60:
                lines.append(cur)
                cur = bytearray()
        if cur:
            lines.append(cur)
        def lit(x):
            return '"' + "".join(chr(b) if 32 <= b < 127 and chr(b) not in '"\\?' else f"\\{b:03o}" for b in x) + '"'
        return f"const char {name}[{len(self.buf) + 1}] =\n" + "\n".join("    " + lit(x) for x in lines) + ";\n"



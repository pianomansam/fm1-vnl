def run(screens_path, out, check):
    try:
        data = json.loads(Path(screens_path).read_text())
        vocab = json.loads((WB / "ui/vocab.json").read_text())
        rows = json.loads((WB / "rows.json").read_text())
        opts = json.loads((WB / "options.json").read_text())
        ch_h, ch_c, all_rows = gen_choices(rows, opts, shown_rows(data))
        parts = part_names(data)
        sc_h, sc_c = gen_screens(data, vocab, all_rows, parts)
    except Refused as e:
        for line in str(e).splitlines():
            print(f"gen: {line}", file=sys.stderr)
        return 1
    files = {"screens_gen.h": sc_h, "screens_gen.c": sc_c, "choices_gen.h": ch_h, "choices_gen.c": ch_c}
    out = Path(out)
    if check:
        stale = [n for n, t in files.items() if not (out / n).exists() or (out / n).read_text() != t]
        if stale:
            print(f"gen: stale: {', '.join(stale)} (run python3 -I tools/screens/gen.py)", file=sys.stderr)
            return 1
        print("gen: check: the screens and choices tables are up to date")
        return 0
    out.mkdir(parents=True, exist_ok=True)
    for n, t in files.items():
        (out / n).write_text(t)
    print(f"gen: wrote {', '.join(files)} in {out}")
    return 0


def main(argv):
    args, check, screens, out = argv[1:], False, WB / "ui/screens.json", ROOT / "app/ui"
    while args:
        a = args.pop(0)
        if a == "--check":
            check = True
        elif a == "--screens":
            screens = args.pop(0)
        elif a == "--out":
            out = args.pop(0)
        else:
            print(__doc__, file=sys.stderr)
            return 2
    return run(screens, out, check)


if __name__ == "__main__":
    sys.exit(main(sys.argv))
